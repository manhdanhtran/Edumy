/**
 * Category administration writes (UC-A06 create, UC-A07 update, UC-A08 delete or deactivate, D-21) through the real
 * filter chain and MySQL: unique name (ai_ci) / slug → 409 {@code CATEGORY_ALREADY_EXISTS}, slug generated by
 * {@code SlugGenerator}, {@link CategoryChanged} on every change, admin only.
 */
@MySqlSpringBootTest
@RecordApplicationEvents
class AdminCategoryWriteIT {

    static final String CATEGORIES = "/api/v1/admin/categories";

    @Autowired
    MockMvc mvc;
    @Autowired
    TestUsers users;
    @Autowired
    JwtTestTokens tokens;
    @Autowired
    JdbcClient jdbc;
    @Autowired
    ApplicationEvents events;

    CourseFixtures fixtures;
    Session admin;
    String unique;

    @BeforeEach
    void setUp() {
        fixtures = new CourseFixtures(jdbc);
        admin = tokens.newUserSession(RoleCode.ADMIN);
        unique = UUID.randomUUID().toString().substring(0, 8);
    }

    @AfterEach
    void cleanUp() {
        fixtures.deleteAll();
        users.deleteAll();
    }

    // ------------------------------------------------------------------------------------------------ UC-A06 create

    @Test
    void create_slugGeneratedFromName_activeByDefault_201_eventPublished_UCA06() throws Exception {
        MvcResult result = mvc.perform(json(post(CATEGORIES), admin,
                        "{\"name\": \"  Lập trình Đồ họa " + unique + "  \"}"))
                .andExpect(status().isCreated())
                .andExpect(jsonPath("$.name").value("Lập trình Đồ họa " + unique))
                .andExpect(jsonPath("$.slug").value("lap-trinh-do-hoa-" + unique))
                .andExpect(jsonPath("$.active").value(true))
                .andExpect(jsonPath("$.courseCount").value(0))
                .andExpect(jsonPath("$.createdAt").isNotEmpty())
                .andExpect(jsonPath("$.updatedAt").isNotEmpty())
                .andReturn();
        long id = idOf(result);

        assertThat(result.getResponse().getHeader(HttpHeaders.LOCATION)).isEqualTo(CATEGORIES + "/" + id);
        assertThat(events.stream(CategoryChanged.class)).containsExactly(new CategoryChanged(id));
    }

    @Test
    void create_withSlugAndInactive_keepsThem_UCA06() throws Exception {
        long id = idOf(mvc.perform(json(post(CATEGORIES), admin,
                        "{\"name\": \"Ẩn " + unique + "\", \"slug\": \"an-tu-chon-" + unique + "\", \"active\": false}"))
                .andExpect(status().isCreated())
                .andExpect(jsonPath("$.slug").value("an-tu-chon-" + unique))
                .andExpect(jsonPath("$.active").value(false))
                .andReturn());

        assertThat(jdbc.sql("SELECT is_active FROM categories WHERE id = ?").param(id).query(Boolean.class).single())
                .isFalse();
    }

    @Test
    void create_nameTakenAccentAndCaseInsensitively_409CategoryAlreadyExists_UCA06() throws Exception {
        create("Thiết kế " + unique);

        MvcResult result = expectProblem(mvc.perform(json(post(CATEGORIES), admin,
                        "{\"name\": \"THIET KE " + unique + "\", \"slug\": \"khac-" + unique + "\"}")),
                409, "CATEGORY_ALREADY_EXISTS");
        jsonPath("$.errors[0].field").value("name").match(result);
        jsonPath("$.errors.length()").value(1).match(result);
        assertThat(events.stream(CategoryChanged.class)).hasSize(1); // only the first create
    }

    @Test
    void create_slugTaken_409CategoryAlreadyExists_onSlug_UCA06() throws Exception {
        create("Kinh doanh " + unique);

        MvcResult result = expectProblem(mvc.perform(json(post(CATEGORIES), admin,
                        "{\"name\": \"Tên khác " + unique + "\", \"slug\": \"kinh-doanh-" + unique + "\"}")),
                409, "CATEGORY_ALREADY_EXISTS");
        jsonPath("$.errors[0].field").value("slug").match(result);
    }

    @Test
    void create_invalidInput_400ValidationFailed() throws Exception {
        expectField(mvc.perform(json(post(CATEGORIES), admin, "{\"name\": \"   \"}")), "name");
        expectField(mvc.perform(json(post(CATEGORIES), admin, "{}")), "name");
        expectField(mvc.perform(json(post(CATEGORIES), admin, "{\"name\": \"" + "a".repeat(101) + "\"}")), "name");
        expectField(mvc.perform(json(post(CATEGORIES), admin,
                "{\"name\": \"Hợp lệ " + unique + "\", \"slug\": \"Co_Dau-\"}")), "slug");
        // nothing to make a slug of
        expectField(mvc.perform(json(post(CATEGORIES), admin, "{\"name\": \"!!!\"}")), "slug");
        assertThat(events.stream(CategoryChanged.class)).isEmpty();
    }

    // ------------------------------------------------------------------------------------------------ UC-A07 update

    @Test
    void update_renameKeepsSlug_slugChangesOnlyWhenSent_UCA07() throws Exception {
        long id = create("Âm nhạc " + unique);

        mvc.perform(json(patch(CATEGORIES + "/" + id), admin, "{\"name\": \"Âm nhạc mới " + unique + "\"}"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.id").value(id))
                .andExpect(jsonPath("$.name").value("Âm nhạc mới " + unique))
                .andExpect(jsonPath("$.slug").value("am-nhac-" + unique))
                .andExpect(jsonPath("$.active").value(true));

        mvc.perform(json(patch(CATEGORIES + "/" + id), admin, "{\"slug\": \"am-nhac-moi-" + unique + "\"}"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.name").value("Âm nhạc mới " + unique))
                .andExpect(jsonPath("$.slug").value("am-nhac-moi-" + unique));

        // the same name again (own row) is not a duplicate
        mvc.perform(json(patch(CATEGORIES + "/" + id), admin, "{\"name\": \"ÂM NHẠC MỚI " + unique + "\"}"))
                .andExpect(status().isOk());
        assertThat(events.stream(CategoryChanged.class)).hasSize(4).allMatch(e -> e.categoryId() == id);
    }

    @Test
    void update_deactivateThenReactivate_UCA07() throws Exception {
        long id = create("Ngoại ngữ " + unique);

        mvc.perform(json(patch(CATEGORIES + "/" + id), admin, "{\"active\": false}"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.active").value(false));
        mvc.perform(json(patch(CATEGORIES + "/" + id), admin, "{\"active\": false}")) // same value: no-op
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.active").value(false));
        mvc.perform(json(patch(CATEGORIES + "/" + id), admin, "{\"active\": true}"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.active").value(true));
    }

    @Test
    void update_nameOrSlugOfAnotherCategory_409_nothingChanges_UCA07() throws Exception {
        create("Tiếp thị " + unique);
        long id = create("Bán hàng " + unique);

        expectProblem(mvc.perform(json(patch(CATEGORIES + "/" + id), admin, "{\"name\": \"tiep thi " + unique + "\"}")),
                409, "CATEGORY_ALREADY_EXISTS");
        expectProblem(mvc.perform(json(patch(CATEGORIES + "/" + id), admin, "{\"slug\": \"tiep-thi-" + unique + "\"}")),
                409, "CATEGORY_ALREADY_EXISTS");

        assertThat(jdbc.sql("SELECT name FROM categories WHERE id = ?").param(id).query(String.class).single())
                .isEqualTo("Bán hàng " + unique);
    }

    @Test
    void update_blankNameOrBadSlug_400() throws Exception {
        long id = create("Sức khỏe " + unique);

        expectField(mvc.perform(json(patch(CATEGORIES + "/" + id), admin, "{\"name\": \" \"}")), "name");
        expectField(mvc.perform(json(patch(CATEGORIES + "/" + id), admin, "{\"slug\": \"-bad\"}")), "slug");
    }

    @Test
    void update_unknownCategory_404() throws Exception {
        expectProblem(mvc.perform(json(patch(CATEGORIES + "/" + Long.MAX_VALUE), admin, "{\"active\": false}")),
                404, "RESOURCE_NOT_FOUND");
    }

    // ------------------------------------------------------------------------------------------------ UC-A08 delete

    @Test
    void delete_unusedCategory_204_rowDeleted_UCA08_D21() throws Exception {
        long id = create("Xóa được " + unique);

        mvc.perform(delete(CATEGORIES + "/" + id).header(HttpHeaders.AUTHORIZATION, admin.bearer()))
                .andExpect(status().isNoContent())
                .andExpect(content().string(""));

        assertThat(jdbc.sql("SELECT COUNT(*) FROM categories WHERE id = ?").param(id).query(Long.class).single())
                .isZero();
        assertThat(events.stream(CategoryChanged.class)).containsExactly(new CategoryChanged(id),
                new CategoryChanged(id));
    }

    @Test
    void delete_usedCategory_onlyDeactivated_200_courseKeepsIt_thenAgain409_UCA08_D21() throws Exception {
        Session instructor = tokens.newUserSession(RoleCode.STUDENT, RoleCode.INSTRUCTOR);
        long id = fixtures.category(true);
        long course = fixtures.draftCourse(instructor.userId(), id);

        mvc.perform(delete(CATEGORIES + "/" + id).header(HttpHeaders.AUTHORIZATION, admin.bearer()))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.id").value(id))
                .andExpect(jsonPath("$.active").value(false))
                .andExpect(jsonPath("$.courseCount").value(1));

        assertThat(jdbc.sql("SELECT category_id FROM courses WHERE id = ?").param(course).query(Long.class).single())
                .isEqualTo(id);
        assertThat(events.stream(CategoryChanged.class)).containsExactly(new CategoryChanged(id));

        // used and already inactive: nothing left to do
        expectProblem(mvc.perform(delete(CATEGORIES + "/" + id).header(HttpHeaders.AUTHORIZATION, admin.bearer())),
                409, "DATA_CONFLICT");
        assertThat(events.stream(CategoryChanged.class)).hasSize(1);
    }

    @Test
    void delete_unknownCategory_404() throws Exception {
        expectProblem(mvc.perform(delete(CATEGORIES + "/" + Long.MAX_VALUE)
                .header(HttpHeaders.AUTHORIZATION, admin.bearer())), 404, "RESOURCE_NOT_FOUND");
    }

    // ------------------------------------------------------------------------------------------------ security

    @Test
    void writes_withoutToken_401() throws Exception {
        long id = fixtures.category(true);

        expectProblem(mvc.perform(post(CATEGORIES).contentType(MediaType.APPLICATION_JSON)
                .content("{\"name\": \"X " + unique + "\"}")), 401, "UNAUTHENTICATED");
        expectProblem(mvc.perform(patch(CATEGORIES + "/" + id).contentType(MediaType.APPLICATION_JSON)
                .content("{\"active\": false}")), 401, "UNAUTHENTICATED");
        expectProblem(mvc.perform(delete(CATEGORIES + "/" + id)), 401, "UNAUTHENTICATED");
    }

    @Test
    void writes_asInstructorOrStudent_403_nothingChanges() throws Exception {
        Session instructor = tokens.newUserSession(RoleCode.STUDENT, RoleCode.INSTRUCTOR);
        long id = fixtures.category(true);

        expectProblem(mvc.perform(json(post(CATEGORIES), instructor, "{\"name\": \"X " + unique + "\"}")),
                403, "ACCESS_DENIED");
        expectProblem(mvc.perform(json(patch(CATEGORIES + "/" + id), instructor, "{\"active\": false}")),
                403, "ACCESS_DENIED");
        expectProblem(mvc.perform(delete(CATEGORIES + "/" + id)
                .header(HttpHeaders.AUTHORIZATION, instructor.bearer())), 403, "ACCESS_DENIED");

        assertThat(jdbc.sql("SELECT is_active FROM categories WHERE id = ?").param(id).query(Boolean.class).single())
                .isTrue();
        assertThat(events.stream(CategoryChanged.class)).isEmpty();
    }

    /** P10 MINOR-1 / BR-26: a token still claiming {@code admin} after the role was revoked in the DB gets 403. */
    @Test
    void writes_adminRoleRevokedInDatabase_staleJwt_403_nothingChanges_BR26() throws Exception {
        Session staleAdmin = tokens.newUserSession(RoleCode.ADMIN);
        users.revokeRole(staleAdmin.userId(), RoleCode.ADMIN); // the JWT still claims admin
        long id = fixtures.category(true);
        String name = "Stale " + unique;

        expectProblem(mvc.perform(json(post(CATEGORIES), staleAdmin, "{\"name\": \"" + name + "\"}")),
                403, "ACCESS_DENIED");
        expectProblem(mvc.perform(json(patch(CATEGORIES + "/" + id), staleAdmin, "{\"active\": false}")),
                403, "ACCESS_DENIED");
        expectProblem(mvc.perform(delete(CATEGORIES + "/" + id)
                .header(HttpHeaders.AUTHORIZATION, staleAdmin.bearer())), 403, "ACCESS_DENIED");

        assertThat(jdbc.sql("SELECT is_active FROM categories WHERE id = ?").param(id).query(Boolean.class).single())
                .isTrue();
        assertThat(jdbc.sql("SELECT COUNT(*) FROM categories WHERE name = ?").param(name).query(Long.class).single())
                .isZero();
        assertThat(events.stream(CategoryChanged.class)).isEmpty();
    }

    // ------------------------------------------------------------------------------------------------ helpers

    /** Creates a category through the API (slug generated) and tracks it for clean-up. */
    private long create(String name) throws Exception {
        return idOf(mvc.perform(json(post(CATEGORIES), admin, "{\"name\": \"" + name + "\"}"))
                .andExpect(status().isCreated())
                .andReturn());
    }

    private long idOf(MvcResult result) throws Exception {
        long id = ((Number) JsonPath.read(result.getResponse().getContentAsString(StandardCharsets.UTF_8), "$.id"))
                .longValue();
        fixtures.trackCategory(id);
        return id;
    }

    private static MockHttpServletRequestBuilder json(MockHttpServletRequestBuilder request, Session caller,
                                                      String body) {
        return request.header(HttpHeaders.AUTHORIZATION, caller.bearer())
                .contentType(MediaType.APPLICATION_JSON)
                .content(body);
    }

    private static void expectField(ResultActions actions, String field) throws Exception {
        MvcResult result = expectProblem(actions, 400, "VALIDATION_FAILED");
        jsonPath("$.errors[*].field", org.hamcrest.Matchers.hasItem(field)).match(result);
        header().doesNotExist(HttpHeaders.LOCATION).match(result);
    }
}
